def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate inputs and detect stale generated files")
    args = parser.parse_args()
    data = json.loads(DATA.read_text(encoding="utf-8"))
    validate(data)
    contents = {"info": {"author": "xcode", "version": 1}}
    generated: dict[Path, bytes] = {}

    def add(path: Path, value: str | dict | bytes) -> None:
        if isinstance(value, dict):
            value = json.dumps(value, ensure_ascii=False, indent=2) + "\n"
        generated[path] = value.encode("utf-8") if isinstance(value, str) else value

    add(ROOT / "Sources/LedgerCore/AccountTemplateCatalog.swift", swift(data))
    add(DATA.parent / "preview.html", preview(data))
    add(ASSETS / "Contents.json", contents)
    # Do not take ownership of a pre-existing application's asset catalog root.
    if not (ASSETS.parent / "Contents.json").exists():
        add(ASSETS.parent / "Contents.json", contents)
    for icon in data["icons"]:
        if not icon["assetName"]:
            continue
        source = ROOT / icon["filePath"]
        image_set = ASSETS / (icon["assetName"] + ".imageset")
        add(image_set / source.name, source.read_bytes())
        image_contents = {"images": [{"filename": source.name, "idiom": "universal"}], **contents,
                          "properties": {"template-rendering-intent": "original"}}
        if source.suffix == ".svg":
            image_contents["properties"]["preserves-vector-representation"] = True
        add(image_set / "Contents.json", image_contents)
    stale = []
    for path, content in generated.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    unexpected = [str(path.relative_to(ROOT)) for path in ASSETS.rglob("*") if path.is_file() and path not in generated]
    if stale or unexpected:
        raise SystemExit("Generated assets need review:\n" + "\n".join(stale + unexpected))
    print(f'{"Checked" if args.check else "Generated"}: {len(data["institutions"])} institutions, {len(data["templates"])} templates, {len(generated)} files.')


if __name__ == "__main__":
    main()
