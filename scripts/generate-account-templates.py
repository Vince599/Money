"""Build offline Swift data, Xcode image sets and a preview from the reviewed catalog.

Run from any directory: python scripts/generate-account-templates.py [--check]
Standard library only. No network access and no source asset modification.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "assets/account-templates/catalog.json"
ASSETS = ROOT / "App/Assets.xcassets/AccountBrands"
GROUPS = {"wallet": "支付钱包", "bank": "银行卡", "creditCard": "信用卡", "storedValue": "话费与储值", "cash": "现金"}


def quoted(value: str) -> str:
    # JSON quoting agrees with Swift for these strings; disallow incompatible Unicode escapes.
    return json.dumps(value, ensure_ascii=False).replace("\\/", "/")


def string_array(values: list[str]) -> str:
    return "[" + ", ".join(quoted(value) for value in values) + "]"


def validate(data: dict) -> None:
    assert data["schemaVersion"] == 1 and data["region"] == "CN"
    for field in ("icons", "institutions", "templates"):
        identifiers = [item["id"] for item in data[field]]
        assert len(identifiers) == len(set(identifiers)), f"Duplicate {field} ID"
        assert all(re.fullmatch(r"[a-z0-9.-]+", key) for key in identifiers)
    icons = {item["id"]: item for item in data["icons"]}
    institutions = {item["id"]: item for item in data["institutions"]}
    asset_names = [item["assetName"] for item in icons.values() if item["assetName"]]
    assert len(asset_names) == len(set(asset_names)), "Duplicate asset name"
    for icon in icons.values():
        assert re.fullmatch(r"#[0-9A-Fa-f]{6}", icon["colorHex"])
        assert icon["fallbackSymbol"] and icon["accessibilityName"]
        if not icon["assetName"]:
            assert not icon.get("filePath"), "Generic icons use SF Symbols"
            continue
        assert re.fullmatch(r"account-brand-[a-z0-9-]+", icon["assetName"])
        path = (ROOT / icon["filePath"]).resolve()
        assert path.is_relative_to(DATA.parent), "Source asset escaped catalog directory"
        content = path.read_bytes()
        assert hashlib.sha256(content).hexdigest() == icon["sha256"], f"Changed source: {path}"
        assert icon["sourceURL"].startswith("https://") and icon["usageNote"]
        if path.suffix == ".svg":
            svg = ET.fromstring(content)
            assert svg.tag.split("}")[-1] == "svg" and svg.get("viewBox")
            for element in svg.iter():
                assert element.tag.split("}")[-1] not in {"script", "foreignObject", "image", "text"}
                for key, value in element.attrib.items():
                    assert not key.lower().startswith("on"), "Event handlers are not allowed"
                    assert "url(" not in value or "url(#" in value, "External SVG resource"
                    if key.split("}")[-1] == "href":
                        assert value.startswith("#"), "External SVG link"
        else:
            assert path.suffix == ".png" and content.startswith(b"\x89PNG\r\n\x1a\n")
    for institution in institutions.values():
        assert institution["iconID"] in icons
    for template in data["templates"]:
        assert template["group"] in GROUPS and template["iconID"] in icons
        assert template["currency"] == "CNY" and type(template["includedInSummary"]) is bool
        assert template["kind"] in {"wallet", "bank", "creditCard", "storedValue", "cash"}
        assert template["nature"] == ("liability" if template["kind"] == "creditCard" else "asset")
        if template["institutionID"]:
            institution = institutions[template["institutionID"]]
            assert institution["iconID"] == template["iconID"]
        if "话费" in template["name"]:
            assert template["kind"] == "storedValue" and not template["includedInSummary"]


def swift(data: dict) -> str:
    lines = ["// Generated by scripts/generate-account-templates.py; edit assets/account-templates/catalog.json.",
             "// This catalog is opt-in presentation data, never a seed account list.",
             "public enum AccountTemplateCatalog {", "    public static let region = \"CN\"", "    public static let icons: [AccountIcon] = ["]
    for item in data["icons"]:
        asset = quoted(item["assetName"]) if item["assetName"] else "nil"
        lines.append(f'        AccountIcon(id: {quoted(item["id"])}, assetName: {asset}, fallbackSymbol: {quoted(item["fallbackSymbol"])}, colorHex: {quoted(item["colorHex"])}, accessibilityName: {quoted(item["accessibilityName"])}),')
    lines += ["    ]", "", "    public static let institutions: [AccountInstitution] = ["]
    for item in data["institutions"]:
        lines.append(f'        AccountInstitution(id: {quoted(item["id"])}, name: {quoted(item["name"])}, shortName: {quoted(item["shortName"])}, aliases: {string_array(item["aliases"])}, iconID: {quoted(item["iconID"])}),')
    lines += ["    ]", "", "    public static let templates: [AccountTemplate] = ["]
    for item in data["templates"]:
        institution = quoted(item["institutionID"]) if item["institutionID"] else "nil"
        lines += [f'        AccountTemplate(id: {quoted(item["id"])}, name: {quoted(item["name"])}, group: .{item["group"]},',
                  f'                        institutionID: {institution}, iconID: {quoted(item["iconID"])}, kind: .{item["kind"]}, nature: .{item["nature"]},',
                  f'                        currency: .cny, includedInSummary: {str(item["includedInSummary"]).lower()}, keywords: {string_array(item["keywords"])},',
                  f'                        note: {quoted(item["note"])}),']
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


